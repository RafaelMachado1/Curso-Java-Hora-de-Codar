/**
 * ============================================================
 *                    HELLO WORLD EM JAVA
 * ============================================================
 *
 * O primeiro programa em Java normalmente exibe uma mensagem
 * simples no console para confirmar que o ambiente está
 * funcionando corretamente.
 *
 * Neste exemplo, usamos:
 *
 * - public class HelloWorld:
 *   define a classe principal do programa.
 *
 * - public static void main(String[] args):
 *   é o método principal, ou seja, o ponto de entrada da
 *   aplicação Java.
 *
 * - System.out.println(...):
 *   imprime uma mensagem no console.
 *
 * Objetivo desta seção:
 * - entender a estrutura básica de um programa Java;
 * - executar o primeiro código;
 * - confirmar que Java e IDE estão funcionando.
 * ============================================================
 */
public class HelloWorld {
    public static void main(String[] args) {
        System.out.println("Hello World!");
    }
}

